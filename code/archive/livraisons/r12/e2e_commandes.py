# Commandes de la borne années 90 : vrais sprites, trois présentations, clics et glissements
from playwright.sync_api import sync_playwright
MOCK = open('/home/claude/mr/tests/mock_ble.js').read()
URL = "http://localhost:8765/code/micro-rider.html"
res = []
def check(n, c, d=""):
    res.append(bool(c)); print(("OK  " if c else "KO  ") + n + ("" if c else "   -> " + str(d)))
HASH = "(()=>{const c=document.querySelector('.ctl'),d=c.getContext('2d').getImageData(%s).data;let h=0;for(let i=0;i<d.length;i+=4){h=(h*31+d[i]+d[i+1]*3+d[i+2]*7+d[i+3])|0}return h})()"
JOY = HASH % "240,975,170,140"; JAUNE = HASH % "590,975,100,140"; ORANGE = HASH % "690,975,100,140"
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1300, "height": 1000}); errs = []
    pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
    pg.add_init_script(MOCK)
    pg.goto(URL); pg.wait_for_timeout(500)
    pg.evaluate("localStorage.clear()"); pg.goto(URL); pg.wait_for_timeout(800)
    pg.click("[data-mode=arcade]"); pg.wait_for_timeout(1200)
    pg.select_option("#borne", "steampunk"); pg.wait_for_timeout(800)
    check("autre borne : pas de sprites (halos)", not pg.evaluate("document.querySelector('.ctl').classList.contains('actif')"))
    pg.select_option("#borne", "original"); pg.wait_for_timeout(1500)
    check("réglage par défaut : sprites + halos", pg.input_value("#commandes") == "sprites-halos")
    check("Années 90, vue entière : le canevas des sprites est actif", pg.evaluate("document.querySelector('.ctl').classList.contains('actif')"))
    check("sprites + halos : les halos restent affichés", pg.evaluate("document.querySelector('.cmd').style.display") == "")
    check("le canevas est dessiné (panneau + sprites)", pg.evaluate(JOY) != 0 and pg.evaluate(JAUNE) != 0)
    pg.screenshot(path="/tmp/cmd_repos.png", clip=dict(zip(["x","y","width","height"], pg.evaluate("(()=>{const r=document.querySelector('.machine').getBoundingClientRect();return [r.x,r.y+r.height*0.6,r.width,r.height*0.2]})()"))))
    h0 = pg.evaluate(JOY)
    # --- joystick par le clavier (gauche/droite : halo + sprite, aucune action)
    pg.evaluate("MR.rapport()"); r0 = pg.evaluate("MR.rapport()")
    pg.click("body", position={"x": 5, "y": 5}); pg.keyboard.down("ArrowLeft"); pg.wait_for_timeout(200); hg = pg.evaluate(JOY)
    check("flèche gauche tenue : le joystick penche à gauche (sprite différent)", hg != h0)
    pg.keyboard.up("ArrowLeft"); pg.wait_for_timeout(200)
    check("flèche relâchée : joystick revenu au centre, rapport inchangé", pg.evaluate(JOY) == h0 and pg.evaluate("MR.rapport()") == r0)
    pg.keyboard.down("ArrowRight"); pg.wait_for_timeout(200); hd = pg.evaluate(JOY); pg.keyboard.up("ArrowRight")
    check("flèche droite : sprite différent du centre et de la gauche", hd != h0 and hd != hg)
    # --- boutons : changement de rapport par le clavier -> le bouton s'enfonce un instant
    j0 = pg.evaluate(JAUNE); o0 = pg.evaluate(ORANGE)
    pg.evaluate("MR.changerRapport(1,'test')"); pg.wait_for_timeout(60)
    check("rapport + : le bouton orange s'enfonce, le jaune non", pg.evaluate(ORANGE) != o0 and pg.evaluate(JAUNE) == j0)
    pg.wait_for_timeout(400)
    check("le bouton orange remonte", pg.evaluate(ORANGE) == o0)
    pg.evaluate("MR.changerRapport(-1,'test')"); pg.wait_for_timeout(60)
    check("rapport − : le bouton jaune s'enfonce", pg.evaluate(JAUNE) != j0 and pg.evaluate(ORANGE) == o0)
    pg.wait_for_timeout(400)
    # --- boost et frein = sprites vers l'écran / vers le joueur
    pg.evaluate("MR.etat.v = 8; MR.etat.boostPret = 0; MR.lancerBoost('test')"); pg.wait_for_timeout(300); hb = pg.evaluate(JOY)
    check("boost : joystick vers l'écran (sprite différent)", hb != h0 and hb != hg and hb != hd)
    pg.evaluate("MR.etat.boostFin = 0"); pg.wait_for_timeout(400)
    pg.evaluate("MR.tenirFrein(true)"); pg.wait_for_timeout(300); hf = pg.evaluate(JOY)
    check("frein : joystick vers le joueur (sprite différent des autres)", hf != h0 and hf != hb and hf != hg and hf != hd)
    pg.evaluate("MR.tenirFrein(false)"); pg.wait_for_timeout(300)
    check("tout relâché : retour au sprite de repos", pg.evaluate(JOY) == h0)
    # --- clics sur la borne
    box = pg.evaluate("(()=>{const r=document.querySelector('.ctl').getBoundingClientRect();return [r.x,r.y,r.width,r.height]})()")
    def pos(x, y): return box[0] + x * box[2] / 1024, box[1] + y * box[3] / 1536
    pg.evaluate("MR.fixerRapport(10,'test')")
    x, y = pos(640, 1050); pg.mouse.move(x, y); pg.mouse.down(); pg.wait_for_timeout(80)
    check("clic maintenu sur le jaune : rapport 9, bouton enfoncé", pg.evaluate("MR.rapport()") == 9 and pg.evaluate(JAUNE) != j0, pg.evaluate("MR.rapport()"))
    pg.wait_for_timeout(500)
    check("jaune toujours enfoncé tant qu'on maintient", pg.evaluate(JAUNE) != j0)
    pg.mouse.up(); pg.wait_for_timeout(100)
    check("relâché : le bouton remonte, le rapport reste 9", pg.evaluate(JAUNE) == j0 and pg.evaluate("MR.rapport()") == 9)
    x, y = pos(736, 1050); pg.mouse.move(x, y); pg.mouse.down(); pg.mouse.up(); pg.wait_for_timeout(60)
    check("clic sur l'orange : rapport 10", pg.evaluate("MR.rapport()") == 10)
    # joystick par glissement
    x, y = pos(322, 1040); pg.mouse.move(x, y); pg.mouse.down(); pg.mouse.move(x, y + 30, steps=4); pg.wait_for_timeout(250)
    check("glisser vers le bas : frein tenu, sprite « vers le joueur »", pg.evaluate("MR.valeurs().frein") is True and pg.evaluate(JOY) == hf, (pg.evaluate("MR.valeurs().frein"),))
    pg.mouse.up(); pg.wait_for_timeout(300)
    check("relâché : frein lâché, joystick au centre", pg.evaluate("MR.valeurs().frein") is False and pg.evaluate(JOY) == h0)
    pg.evaluate("MR.etat.v = 8; MR.etat.boostPret = 0")
    x, y = pos(322, 1040); pg.mouse.move(x, y); pg.mouse.down(); pg.mouse.move(x, y - 30, steps=4); pg.wait_for_timeout(300)
    check("glisser vers le haut : boost lancé", pg.evaluate("MR.valeurs().boost.actif") is True, pg.evaluate("MR.valeurs().boost"))
    pg.mouse.up(); pg.evaluate("MR.etat.boostFin = 0"); pg.wait_for_timeout(500)
    x, y = pos(322, 1040); pg.mouse.move(x, y); pg.mouse.down(); pg.mouse.move(x - 30, y, steps=4); pg.wait_for_timeout(200)
    check("glisser vers la gauche : sprite penché, aucune action", pg.evaluate(JOY) == hg and pg.evaluate("MR.rapport()") == 10 and pg.evaluate("MR.valeurs().frein") is False)
    pg.mouse.up(); pg.wait_for_timeout(200)
    x, y = pos(500, 800); r1 = pg.evaluate("MR.rapport()"); pg.mouse.click(x, y); pg.wait_for_timeout(100)
    check("clic ailleurs sur la borne : rien ne se passe", pg.evaluate("MR.rapport()") == r1)
    # --- présentations
    pg.select_option("#commandes", "sprites"); pg.wait_for_timeout(300)
    check("sprites seuls : halos cachés, sprites actifs", pg.evaluate("document.querySelector('.cmd').style.display") == "none" and pg.evaluate("document.querySelector('.ctl').classList.contains('actif')"))
    pg.select_option("#commandes", "halos"); pg.wait_for_timeout(300)
    check("halos seuls : canevas inactif, halos affichés", not pg.evaluate("document.querySelector('.ctl').classList.contains('actif')") and pg.evaluate("document.querySelector('.cmd').style.display") == "")
    pg.select_option("#commandes", "sprites-halos"); pg.wait_for_timeout(300)
    check("retour à sprites + halos", pg.evaluate("document.querySelector('.ctl').classList.contains('actif')"))
    pg.evaluate("localStorage.length"); pg.wait_for_timeout(300)
    pg.select_option("#commandes", "sprites"); pg.evaluate("localStorage.length"); pg.wait_for_timeout(400)
    pg.goto(URL); pg.wait_for_timeout(2500)
    check("le choix de présentation est mémorisé", pg.input_value("#commandes") == "sprites", pg.input_value("#commandes"))
    # --- vue « jeu » : pas de sprites (autre image de borne)
    pg.click("#bascule"); pg.wait_for_timeout(1500)
    check("vue jeu : sprites inactifs (halos à la place)", not pg.evaluate("document.querySelector('.ctl').classList.contains('actif')") and pg.evaluate("document.querySelector('.cmd').style.display") == "")
    pg.click("#bascule"); pg.wait_for_timeout(1500)
    check("retour vue entière : sprites actifs", pg.evaluate("document.querySelector('.ctl').classList.contains('actif')"))
    pg.screenshot(path="/tmp/cmd_borne.png")
    check("aucune erreur JavaScript", not errs, errs)
    b.close()
print(sum(res), "OK,", len(res) - sum(res), "KO")
